const ARABIC = /[\u0600-\u06FF\u0750-\u077F]/;
const ARABIC_LETTER = '\u0600-\u06FF\u0750-\u077F';

// Short fragments are only replaced when they stand alone, otherwise "من"
// would eat the first two letters of "منصة" — see buildAllRules below.

// Every whole string is also usable as a fragment: "\u062a\u0639\u0630\u0631 \u062a\u062d\u0645\u064a\u0644 X:" followed by an
// HTTP status is one string to the DOM but a dictionary key plus a number.
// Built on first miss so the common path (exact hit) pays nothing for it.
let allRules = null;

function buildAllRules() {
  // FRAGMENTS first, so on an equal-length tie the fragment wins: "طلب" as a
  // fragment is a count ("orders"), as a dictionary entry it is a noun.
  const combined = FRAGMENTS.concat(
    Object.entries(DICTIONARY).filter(([ar]) => ARABIC.test(ar))
  );
  combined.sort((a, b) => b[0].length - a[0].length);
  return combined.map(([ar, en]) => {
    if (ar.length <= 3 && new RegExp(`^[${ARABIC_LETTER}]+$`).test(ar)) {
      return [new RegExp(`(?<![${ARABIC_LETTER}])${ar}(?![${ARABIC_LETTER}])`, 'g'), en];
    }
    return [ar, en];
  });
}

// toLocaleString('en-US') renders Arabic-Indic digits, so "499" reached an
// English screen as "٤٩٩". Normalising here covers every call site at once.
const AR_DIGITS = '\u0660\u0661\u0662\u0663\u0664\u0665\u0666\u0667\u0668\u0669';
const EXT_AR_DIGITS = '\u06F0\u06F1\u06F2\u06F3\u06F4\u06F5\u06F6\u06F7\u06F8\u06F9';

function westernDigits(text) {
  return text.replace(/[\u0660-\u0669\u06F0-\u06F9]/g, (d) => {
    const i = AR_DIGITS.indexOf(d);
    return String(i >= 0 ? i : EXT_AR_DIGITS.indexOf(d));
  });
}

function translateText(input) {
  const value = westernDigits(input);
  const trimmed = value.trim();
  if (!trimmed || !ARABIC.test(trimmed)) return value;

  const whole = DICTIONARY[trimmed];
  if (whole) return value.replace(trimmed, whole);

  if (!allRules) allRules = buildAllRules();
  let out = value;
  for (const [pattern, en] of allRules) {
    if (typeof pattern === 'string') {
      if (out.includes(pattern)) out = out.split(pattern).join(en);
    } else {
      out = out.replace(pattern, en);
    }
    if (!ARABIC.test(out)) return out;
  }

  // All or nothing. Anything the rules could not finish contains data — a
  // rider's name, a shift the customer named, a city — and half-translating it
  // produces "shift مسائية", which is worse than leaving it in Arabic. A
  // leftover Arabic run is the signal that this string was never UI chrome.
  return value;
}

const TRANSLATABLE_ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE']);

export function translateNode(node) {
  if (!node || getLang() !== 'en') return;

  if (node.nodeType === 3 /* TEXT_NODE */) {
    const next = translateText(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== 1 /* ELEMENT_NODE */) return;
  if (SKIP_TAGS.has(node.tagName) || node.hasAttribute('data-no-i18n')) return;

  for (const attr of TRANSLATABLE_ATTRS) {
    const value = node.getAttribute(attr);
    if (value && ARABIC.test(value)) {
      const next = translateText(value);
      if (next !== value) node.setAttribute(attr, next);
    }
  }
  // Button faces are values, not text, and are user-visible.
  if (node.tagName === 'INPUT') {
    const type = (node.getAttribute('type') || '').toLowerCase();
    if (type === 'button' || type === 'submit' || type === 'reset') {
      const value = node.value;
      if (value && ARABIC.test(value)) node.value = translateText(value);
    }
    return;
  }

  node.childNodes.forEach(translateNode);
}

let observer = null;

// Views render asynchronously — a screen fetches, then writes its markup, then
// a modal writes more on top. Translating once after go() would miss all of
// that, so watch instead. childList only: rewriting a text node does not fire
// a childList record, so this cannot feed itself.
export function startAutoTranslate() {
  if (getLang() !== 'en' || observer) return;

  document.title = translateText(document.title);
  // Dialog text never enters the DOM, so the observer cannot reach it.
  const nativeAlert = window.alert.bind(window);
  const nativeConfirm = window.confirm.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.alert = (m) => nativeAlert(translateText(String(m)));
  window.confirm = (m) => nativeConfirm(translateText(String(m)));
  window.prompt = (m, d) => nativePrompt(translateText(String(m)), d == null ? d : translateText(String(d)));

  translateNode(document.body);
  observer = new MutationObserver((records) => {
    for (const record of records) {
      record.addedNodes.forEach(translateNode);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
  return observer;
}

export function stopAutoTranslate() {
  if (observer) observer.disconnect();
  observer = null;
}

